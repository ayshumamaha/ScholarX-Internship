from flask import Flask, request, jsonify
from PIL import Image
import numpy as np
import io

app = Flask(__name__)

# Training data
training_features = []
training_labels = []

# Generate sample images and train the classifier
def train_model():

    colors = {
        "Red": (255, 0, 0),
        "Green": (0, 255, 0),
        "Blue": (0, 0, 255)
    }

    for label, color in colors.items():

        for i in range(5):

            # Create sample image with slight colour variation
            variation = i * 5

            r = min(255, color[0] - variation)
            g = min(255, color[1] - variation)
            b = min(255, color[2] - variation)

            image = Image.new("RGB", (50, 50), (r, g, b))

            # Extract average RGB values
            feature = np.array(image).mean(axis=(0, 1))

            training_features.append(feature)
            training_labels.append(label)

    print("Image classification model trained successfully!")


# Extract features from uploaded image
def extract_features(image):

    image = image.convert("RGB")
    image = image.resize((50, 50))

    pixels = np.array(image)

    return pixels.mean(axis=(0, 1))


# Predict image category
def predict_image(image):

    feature = extract_features(image)

    distances = []

    for sample in training_features:

        distance = np.linalg.norm(feature - sample)
        distances.append(distance)

    best_index = np.argmin(distances)

    return training_labels[best_index]


# Home page
@app.route("/")
def home():

    return """
    <h1>Image Prediction API</h1>
    <p>Upload an image to predict its dominant colour.</p>

    <form action="/predict" method="POST"
          enctype="multipart/form-data">

        <input type="file" name="image" accept="image/*" required>
        <button type="submit">Predict Image</button>

    </form>

    <p>Supported categories: Red, Green and Blue</p>
    """


# Prediction API
@app.route("/predict", methods=["POST"])
def predict():

    if "image" not in request.files:
        return jsonify({"error": "No image uploaded"}), 400

    file = request.files["image"]

    if file.filename == "":
        return jsonify({"error": "Please select an image"}), 400

    try:

        image = Image.open(io.BytesIO(file.read()))

        result = predict_image(image)

        return jsonify({
            "prediction": result,
            "message": "Image classified successfully"
        })

    except Exception:
        return jsonify({"error": "Invalid image file"}), 400


# Start application
if __name__ == "__main__":

    train_model()

    print("\nIMAGE PREDICTION API STARTED")
    print("Open http://127.0.0.1:5000 in your browser.")

    app.run(host="127.0.0.1", port=5000, debug=False)