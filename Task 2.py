import string

# Knowledge base containing questions and answers
knowledge_base = {
    "hello": "Hello! Welcome to the chatbot.",
    "what is python": "Python is a popular programming language.",
    "what is machine learning": "Machine learning allows computers to learn from data.",
    "what is artificial intelligence": "Artificial Intelligence enables machines to perform tasks that normally require human intelligence.",
    "what is a variable": "A variable is a name used to store data in a program.",
    "what is flask": "Flask is a lightweight Python web framework.",
    "what is a chatbot": "A chatbot is a program that communicates with users.",
    "what is data science": "Data science involves analysing data to find useful information.",
    "what is programming": "Programming is the process of writing instructions for a computer.",
    "thank you": "You're welcome! Have a great day."
}

# Function to clean and process text
def process_text(text):
    text = text.lower()
    text = text.translate(str.maketrans("", "", string.punctuation))
    return set(text.split())


# Function to retrieve the best answer
def get_answer(user_question):

    user_words = process_text(user_question)

    if not user_words:
        return "Please enter a valid question."

    best_score = 0
    best_answer = None

    for question, answer in knowledge_base.items():

        stored_words = process_text(question)

        common_words = user_words.intersection(stored_words)

        score = len(common_words) / len(stored_words)

        if score > best_score:
            best_score = score
            best_answer = answer

    if best_score >= 0.4:
        return best_answer

    return "Sorry, I don't know the answer. Please ask another question."


# Main chatbot
print("RETRIEVAL-BASED CHATBOT")
print("Type 'exit' to stop.")

while True:

    user_input = input("\nYou: ")

    if user_input.lower().strip() == "exit":
        print("Chatbot: Goodbye!")
        break

    response = get_answer(user_input)

    print("Chatbot:", response)