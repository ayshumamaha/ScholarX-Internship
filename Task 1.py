# Commented out IPython magic to ensure Python compatibility.
# %pip install scikit-learn

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB

# Sample training documents
documents = [
    "Python programming and software development",
    "Artificial intelligence and computer technology",
    "Computer hardware software and coding",
    "Machine learning and data science",
    "The latest technology and computer applications",

    "Cricket match and football tournament",
    "The player scored a goal in football",
    "Sports competition and cricket players",
    "Olympic games and sports activities",
    "The team won the cricket championship",

    "Business companies and financial markets",
    "Stock market and business investment",
    "Company profits and economic growth",
    "Marketing and business management",
    "Entrepreneurs starting a new business"
]

categories = [
    "Technology", "Technology", "Technology",
    "Technology", "Technology",

    "Sports", "Sports", "Sports",
    "Sports", "Sports",

    "Business", "Business", "Business",
    "Business", "Business"
]

# Convert text into numerical features
vectorizer = TfidfVectorizer()
X = vectorizer.fit_transform(documents)

# Train the model
model = MultinomialNB()
model.fit(X, categories)

print("DOCUMENT CLASSIFIER")
print("Model trained successfully!")

# Predict new documents
while True:
    text = input("\nEnter a document (or type exit): ")

    if text.lower() == "exit":
        print("Program ended.")
        break

    if not text.strip():
        print("Please enter some text.")
        continue

    new_text = vectorizer.transform([text])
    prediction = model.predict(new_text)

    print("Predicted Category:", prediction[0])